#인자가 없으면 사용법을 출력하고 exit 1 로 끝낸다.
#같은 이름의 폴더가 이미 있으면 덮어쓰지 않고 오류 메시지를 낸 뒤 끝낸다.
#정상적으로 끝나면 만들어진 구조를 보여 준다.
#스크립트 맨 위에 무엇을 하는 스크립트인지 주석으로 적는다.
#-d 는 해당 폴더가 존재하면 참
#-z 는 문자열이 비어있으면 참

#!/usr/bin/bash
# 새 프로젝트 폴더를 생성하고 구조를 보여주는 스크립트

NAME=$1

if [ -z "$NAME" ]; then
    echo "사용법: $0 <폴더이름>"
    exit 1
fi

if [ -d "$NAME" ]; then
    echo "오류: $NAME 폴더가 이미 존재합니다"
    exit 1
fi

mkdir $NAME
echo "$NAME 폴더를 만들었습니다"
tree $NAME